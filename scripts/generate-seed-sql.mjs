// Generates supabase/seed.sql from src/data/seed/catalog.json so the demo
// backend and the Supabase seed always contain the same sample catalog.
// Usage: node scripts/generate-seed-sql.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const catalog = JSON.parse(readFileSync(join(root, 'src/data/seed/catalog.json'), 'utf8'));

const q = (v) => (v === null || v === undefined ? 'null' : typeof v === 'number' || typeof v === 'boolean' ? String(v) : `'${String(v).replace(/'/g, "''")}'`);
const arr = (xs) => `array[${xs.map(q).join(', ')}]::text[]`;
const rows = (xs) => xs.join(',\n  ');

const out = [];
out.push('-- GENERATED by scripts/generate-seed-sql.mjs from src/data/seed/catalog.json — do not edit by hand.');
out.push('-- DEVELOPMENT SAMPLE DATA: illustrative hotels, prices, ratings and inventory, not live availability.');
out.push('-- Photos are keys of images bundled with the app (src/data/photos.ts); a full https URL also works.\n');

out.push(`insert into public.amenities (id, label, icon) values\n  ${rows(catalog.amenities.map((a) => `(${q(a.id)}, ${q(a.label)}, ${q(a.icon)})`))};\n`);

out.push(`insert into public.destinations (id, name, country, blurb, photo, areas, lat, lng, sort_order) values\n  ${rows(
  catalog.destinations.map((d, i) => `(${q(d.id)}, ${q(d.name)}, ${q(d.country)}, ${q(d.blurb)}, ${q(d.photo)}, ${arr(d.areas)}, ${d.lat}, ${d.lng}, ${i})`),
)};\n`);

out.push(`insert into public.hotels (id, destination_id, name, area, address, location_note, description, property_type, rating, review_count, highlights, check_in_time, check_out_time, resort_fee_per_night_cents, tax_rate_bps, lat, lng, is_sample, sort_order) values\n  ${rows(
  catalog.hotels.map(
    (h, i) =>
      `(${q(h.id)}, ${q(h.destinationId)}, ${q(h.name)}, ${q(h.area)}, ${q(h.address)}, ${q(h.locationNote)}, ${q(h.description)}, ${q(h.propertyType)}, ${h.rating}, ${h.reviewCount}, ${arr(h.highlights)}, ${q(h.checkInTime)}, ${q(h.checkOutTime)}, ${h.resortFeePerNightCents}, ${h.taxRateBps}, ${h.lat}, ${h.lng}, true, ${i})`,
  ),
)};\n`);

out.push(`insert into public.hotel_images (hotel_id, position, photo) values\n  ${rows(catalog.hotels.flatMap((h) => h.photos.map((p, i) => `(${q(h.id)}, ${i}, ${q(p)})`)))};\n`);

out.push(`insert into public.hotel_amenities (hotel_id, amenity_id) values\n  ${rows(catalog.hotels.flatMap((h) => h.amenityIds.map((a) => `(${q(h.id)}, ${q(a)})`)))};\n`);

out.push(`insert into public.room_types (id, hotel_id, name, category, photo, size_m2, bed, max_guests, price_per_night_cents, free_cancel_days, breakfast_included, features, inventory, badge, sort_order) values\n  ${rows(
  catalog.hotels.flatMap((h) =>
    h.rooms.map(
      (r, i) =>
        `(${q(r.id)}, ${q(h.id)}, ${q(r.name)}, ${q(r.category)}, ${q(r.photo)}, ${r.sizeM2}, ${q(r.bed)}, ${r.maxGuests}, ${r.pricePerNightCents}, ${q(r.freeCancelDays)}, ${r.breakfastIncluded}, ${arr(r.features)}, ${r.inventory}, ${q(r.badge ?? null)}, ${i})`,
    ),
  ),
)};\n`);

writeFileSync(join(root, 'supabase/seed.sql'), out.join('\n'));
console.log(`supabase/seed.sql: ${catalog.hotels.length} hotels, ${catalog.hotels.reduce((n, h) => n + h.rooms.length, 0)} room types`);
