export type IconName = keyof typeof icons;

export function isIconName(name: string): name is IconName {
  return name in icons;
}

export function Icon({
  name,
  size = 20,
  color = 'text',
  fill,
  strokeWidth = 2,
}: {
  name: IconName;
  size?: number;
  color?: ColorToken;
  /** Solid fill (e.g. the filled heart and star in the design). */
  fill?: ColorToken;
  strokeWidth?: number;
}) {
  const Cmp = icons[name];
  return <Cmp size={size} color={colors[color]} strokeWidth={strokeWidth} fill={fill ? colors[fill] : 'none'} />;
}
